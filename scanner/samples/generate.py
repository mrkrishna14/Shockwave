"""Regenerate the sample ScanResult artifacts from examples/consumers.

Run from repo root: python -m scanner.samples.generate
Uses test-double endpoint/snapshot IDs (real ones are generated by Ishan).
"""
import json
import sys
import uuid
from datetime import datetime, timezone
from pathlib import Path

from scanner import scan_repository
from scanner.contracts import Endpoint, RepositorySnapshot, ScanRequest

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent

_TEST_NAMESPACE = uuid.UUID("2b0f6a52-7f1c-5d6e-9a3b-4c5d6e7f8091")


def tid(name: str) -> str:
    """Deterministic UUID for a test-double name (shared.schemas IDs are UUIDs)."""
    return str(uuid.uuid5(_TEST_NAMESPACE, name))


CATALOG = [
    Endpoint(id=tid("ep-demo-payments-get-v1-charges-id"), service_id="demo-payments", method="GET",
             path="/v1/charges/{id}", snapshot_id=tid("snap-demo-payments-old"), request_schema={}, response_schema={}, evidence=[], reconciliation="not_compared", confidence="direct"),
    Endpoint(id=tid("ep-stripe-post-v1-payment-intents"), service_id="stripe", method="POST",
             path="/v1/payment_intents", snapshot_id=tid("snap-stripe-openapi"), request_schema={}, response_schema={}, evidence=[], reconciliation="not_compared", confidence="direct"),
]
SNAPSHOT = RepositorySnapshot(
    id=tid("snap-consumer-1"), repository_connection_id=tid("rc-consumer-1"),
    commit_sha="3f9c2a1b7d4e5f60718293a4b5c6d7e8f9012345",
    fetched_at=datetime(2026, 10, 17, 10, 0, tzinfo=timezone.utc), content_hash="sha256:test",
)
CASES = {
    "demo_payments_scan_result.json": ("demo-payments", ROOT / "examples/consumers"),
    "stripe_merchant_scan_result.json": ("stripe", ROOT / "examples/consumers/stripe-merchant"),
}


def build(service_id: str, root: Path):
    req = ScanRequest(repository_snapshot_id=SNAPSHOT.id, enrollment_id=tid("enr-1"), service_id=service_id,
                      endpoint_catalog=CATALOG, supported_languages=["python", "javascript", "typescript"])
    result = scan_repository(req, SNAPSHOT, root, consumer_org_id=tid("org-consumer-1"))
    # Drop cache-directory noise (e.g. __pycache__) so samples are environment-independent.
    result.warnings = [w for w in result.warnings if "__pycache__" not in w and ".pytest_cache" not in w]
    return result


def main() -> int:
    for name, (svc, root) in CASES.items():
        (OUT / name).write_text(build(svc, root).model_dump_json(indent=2) + "\n")
        print("wrote", OUT / name)
    return 0


if __name__ == "__main__":
    sys.exit(main())
