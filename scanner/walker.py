"""Read-only file walker restricted to a snapshot root.

Never follows symlinks, never writes, never executes. Every exclusion is
recorded so coverage reporting stays honest: a skipped file is unknown, not
dependency-free.
"""
from __future__ import annotations

import os
import stat
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath

LANGUAGE_BY_SUFFIX = {
    ".py": "python",
    ".js": "javascript",
    ".jsx": "javascript",
    ".mjs": "javascript",
    ".cjs": "javascript",
    ".ts": "typescript",
    ".tsx": "typescript",
    ".mts": "typescript",
    ".cts": "typescript",
}

EXCLUDED_DIRS = {
    ".git", ".hg", ".svn", "node_modules", "bower_components", "vendor",
    "third_party", ".venv", "venv", "env", "site-packages", "__pycache__",
    "dist", "build", "out", ".next", ".nuxt", "coverage", ".tox", ".mypy_cache",
    ".pytest_cache", ".turbo", ".cache",
}
LOCKFILES = {
    "package-lock.json", "npm-shrinkwrap.json", "yarn.lock", "pnpm-lock.yaml",
    "bun.lockb", "poetry.lock", "Pipfile.lock", "uv.lock", "pdm.lock",
}
GENERATED_SUFFIXES = (".min.js", ".bundle.js", ".d.ts", ".map", "_pb2.py", ".pb.go")
GENERATED_MARKERS = (b"@generated", b"DO NOT EDIT", b"auto-generated", b"autogenerated")
MAX_FILE_BYTES = 512 * 1024


@dataclass(frozen=True)
class SourceFile:
    rel_path: str  # POSIX, repository-relative
    language: str
    data: bytes


@dataclass
class WalkResult:
    files: list[SourceFile] = field(default_factory=list)
    skipped: list[tuple[str, str]] = field(default_factory=list)  # (path, reason)
    skipped_dirs: list[tuple[str, str]] = field(default_factory=list)


def _rel(root: Path, p: Path) -> str:
    return PurePosixPath(p.relative_to(root).as_posix()).as_posix()


def walk_repository(
    repo_root: Path,
    languages: set[str] | None = None,
    max_file_bytes: int = MAX_FILE_BYTES,
) -> WalkResult:
    root = Path(repo_root)
    if root.is_symlink() or not root.is_dir():
        raise ValueError("repo_root must be a real directory")
    root = root.resolve()
    result = WalkResult()

    # Deterministic, iterative traversal; os.walk with followlinks=False.
    for dirpath, dirnames, filenames in os.walk(root, followlinks=False):
        current = Path(dirpath)
        keep = []
        for d in sorted(dirnames):
            full = current / d
            rel = _rel(root, full)
            if full.is_symlink():
                result.skipped_dirs.append((rel, "symlink_dir_not_followed"))
            elif d in EXCLUDED_DIRS or d.endswith(".egg-info"):
                result.skipped_dirs.append((rel, "excluded_dir"))
            else:
                keep.append(d)
        dirnames[:] = keep

        for name in sorted(filenames):
            full = current / name
            rel = _rel(root, full)
            suffix = full.suffix.lower()
            language = LANGUAGE_BY_SUFFIX.get(suffix)
            if name in LOCKFILES:
                result.skipped.append((rel, "lockfile"))
                continue
            if language is None:
                continue  # not a candidate source file; not counted
            if name.endswith(GENERATED_SUFFIXES):
                result.skipped.append((rel, "generated"))
                continue
            try:
                st = os.lstat(full)
            except OSError:
                result.skipped.append((rel, "unreadable"))
                continue
            if stat.S_ISLNK(st.st_mode):
                try:
                    target = full.resolve(strict=True)
                    inside = target.is_relative_to(root)
                except (OSError, RuntimeError):
                    inside = False
                result.skipped.append(
                    (rel, "symlink_inside_root_not_followed" if inside else "symlink_escapes_root")
                )
                continue
            if not stat.S_ISREG(st.st_mode):
                result.skipped.append((rel, "not_regular_file"))
                continue
            if st.st_size > max_file_bytes:
                result.skipped.append((rel, "too_large"))
                continue
            if languages and language not in languages:
                result.skipped.append((rel, f"language_not_requested:{language}"))
                continue
            try:
                # O_NOFOLLOW closes the race between lstat and open on POSIX.
                flags = os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0)
                fd = os.open(full, flags)
                with os.fdopen(fd, "rb") as fh:
                    data = fh.read(max_file_bytes + 1)
            except OSError:
                result.skipped.append((rel, "unreadable"))
                continue
            if b"\x00" in data[:8192]:
                result.skipped.append((rel, "binary"))
                continue
            head = data[:600]
            if any(m in head for m in GENERATED_MARKERS):
                result.skipped.append((rel, "generated"))
                continue
            try:
                data.decode("utf-8")
            except UnicodeDecodeError:
                result.skipped.append((rel, "not_utf8"))
                continue
            result.files.append(SourceFile(rel, language, data))

    result.files.sort(key=lambda f: f.rel_path)
    result.skipped.sort()
    result.skipped_dirs.sort()
    return result
