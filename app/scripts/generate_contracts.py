"""Generate JSON Schema and TypeScript directly from the canonical Pydantic models."""
import inspect
import json
from pathlib import Path
from shared import schemas
from backend.demo import endpoint, OLD, NEW, ENDPOINT

ROOT=Path(__file__).resolve().parents[1]
def ts(s):
    if '$ref' in s: return s['$ref'].split('/')[-1]
    if 'const' in s: return json.dumps(s['const'])
    if 'enum' in s: return ' | '.join(json.dumps(x) for x in s['enum'])
    if 'anyOf' in s: return ' | '.join(ts(x) for x in s['anyOf'])
    t=s.get('type')
    if t=='array': return '('+ts(s['items'])+')[]'
    if t=='object':
        if not s.get('properties'): return 'Record<string, unknown>'
        return '{ '+ '; '.join(k+('' if k in s.get('required',[]) else '?')+': '+ts(v) for k,v in s['properties'].items())+' }'
    return {'string':'string','integer':'number','number':'number','boolean':'boolean','null':'null'}.get(t,'unknown')
models={name:cls for name,cls in inspect.getmembers(schemas,inspect.isclass) if issubclass(cls,schemas.Model) and cls.__module__==schemas.__name__}
all_schemas={name:cls.model_json_schema() for name,cls in models.items()}
(ROOT/'shared/contracts.schema.json').write_text(json.dumps(all_schemas,indent=2)+'\n')
(ROOT/'frontend/contracts.ts').write_text('// Generated by scripts/generate_contracts.py; do not edit.\n'+'\n'.join('export type '+name+' = '+ts(schema)+';' for name,schema in all_schemas.items())+'\n')
(ROOT/'shared/demo-identities.json').write_text(json.dumps({'service_id':'demo-payments','old_snapshot_id':OLD,'new_snapshot_id':NEW,'endpoint_id':ENDPOINT,'endpoint':endpoint().model_dump(mode='json')},indent=2)+'\n')
print(f'Generated {len(models)} canonical contract types')
