def test_results_match_the_checked_in_reference_byte_for_byte(demo_run: DemoRun) -> None:
    produced = sorted(path.relative_to(demo_run.results).as_posix() for path in demo_run.results.rglob("*") if path.is_file())
    expected = sorted(path.relative_to(EXPECTED).as_posix() for path in EXPECTED.rglob("*") if path.is_file())
    assert produced == expected
    different = [item for item in produced if (demo_run.results / item).read_bytes() != (EXPECTED / item).read_bytes()]
    assert different == [], f"regenerate with `demo.py all --update-expected` only if the change is intended: {different}"
    assert "results/ is byte-identical to demo/expected/results" in demo_run.output


def test_inventory_counts_equal_an_independent_parse_of_the_pinned_bytes(demo_run: DemoRun) -> None:
    pin = load(PIN)
    data = gzip.decompress((PIN.parent / pin["vendored_file"]).read_bytes())
    assert hashlib.sha256(data).hexdigest() == pin["content"]["sha256"]
    spec = json.loads(data)
    by_method: dict[str, int] = {}
    for item in spec["paths"].values():
        for method in HTTP_METHODS:
            if method in item:
                by_method[method.upper()] = by_method.get(method.upper(), 0) + 1
    inventory = load(demo_run.results / "inventory.json")
    counts = inventory["counts"]
    assert counts["paths"] == len(spec["paths"])
    assert counts["operations"] == counts["endpoints"] == sum(by_method.values())
    assert counts["by_method"] == by_method
    assert counts["component_schemas"] == len(spec["components"]["schemas"])
    assert inventory["contract"]["sha256"] == hashlib.sha256(data).hexdigest()
    assert inventory["contract"]["api_version"] == spec["info"]["version"]
    assert inventory["provider_source_access"]["status"] == "unavailable"
    amount = inventory["endpoint"]["response"]["amount"]
    raw_amount = spec["components"]["schemas"]["payment_intent"]["properties"]["amount"]
    assert (amount["type"], amount["description"]) == ("integer", raw_amount["description"])
    names = {(item["name"], item["in"]) for item in inventory["endpoint"]["parameters"]}
    raw = spec["paths"]["/v1/payment_intents/{intent}"]["get"]["parameters"]
    assert names == {(item["name"], item["in"]) for item in raw}


def test_exactly_two_verified_regressions_with_their_guards_passing(demo_run: DemoRun) -> None:
    results = load(demo_run.results / "verification" / "results.json")
    statuses = sorted(item["status"] for item in results)
    assert statuses == ["not_run", "verified_regression", "verified_regression"]
    for result in results:
        if result["status"] == "verified_regression":
            assert result["summary"].startswith("LOCAL RUNNER DOUBLE (trusted local fixtures; plain subprocess")
            assert result["baseline"]["exit_code"] == 0 and result["proposed"]["exit_code"] == 1
    checkout = run_record(demo_run, "execute.checkout-display.proposed")
    relevant = case(checkout, "displayed_total_usd")
    assert (relevant["role"], relevant["status"], relevant["expected"], relevant["actual"]) == (
        "relevant",
        "failed",
        "$10.00",
        "$0.10",
    )
    assert relevant["detail"] == "expected $10.00, actual $0.10"
    assert case(checkout, "tax_note_unchanged")["status"] == "passed"
    fraud = run_record(demo_run, "execute.fraud-threshold.proposed")
    above = case(fraud, "above_threshold_flagged")
    assert (above["role"], above["status"], above["expected"], above["actual"]) == ("relevant", "failed", True, False)
    for guard in ("below_threshold_not_flagged", "at_threshold_not_flagged"):
        assert case(fraud, guard)["status"] == "passed"
    for run_id in ("execute.checkout-display.baseline", "execute.fraud-threshold.baseline"):
        record = run_record(demo_run, run_id)
        assert record["outcome"] == "passed" and record["exit_code"] == 0
        assert all(item["status"] == "passed" for item in record["assertions"])
    for record in (checkout, fraud):
        for item in record["assertions"]:
            for request in item["requests"]:
                assert request["method"] == "GET" and request["path"].startswith("/v1/payment_intents/pi_demo_")
                assert request["stripe_version"] == "2026-09-30.endive"
                assert request["authorization"] == "test_mode_bearer"


