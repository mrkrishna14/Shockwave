def test_storage_risk_is_not_run_with_missing_evidence(demo_run: DemoRun) -> None:
    findings = load(demo_run.results / "consumers" / "shockwave-stripe-reporting" / "findings.json")
    (risk,) = findings["risks"]
    assert (risk["category"], risk["severity"], risk["state"]) == ("storage", "medium", "predicted")
    assert risk["verification"]["status"] == "not_run"
    summary = risk["verification"]["summary"]
    assert "Potential storage risk, not verified" in summary
    assert "Missing evidence: an executable storage scenario; units/schema of the destination" in summary
    plans = load(demo_run.results / "verification" / "plans.json")
    assert risk["risk_id"] not in {plan["risk_id"] for plan in plans}
    assert [item["status"] for item in findings["controls"]] == ["passed", "passed"]
    (observation,) = findings["observations"]
    assert observation["failing_tests"] == ["tests/test_reporting.py::test_ledger_records_stripe_amounts"]
    assert "stays not_run" in observation["statement"]


def test_migrations_validate_with_the_pinned_caveat_and_record_deployment_evidence(demo_run: DemoRun) -> None:
    validation = load(demo_run.results / "migrations" / "validation.json")
    by_id = {item["migration_id"]: item for item in validation["migrations"]}
    assert sorted(by_id) == ["checkout-display-major-units", "fraud-threshold-major-units"]
    for item in by_id.values():
        assert item["status"] == "validated"
        assert item["patched_proposed"]["status"] == "validated"
        assert item["patched_proposed"]["reason"].endswith(PINNED_PATCH_CAVEAT)
        assert item["deployment_assumption"]["is_regression"] is False
        assert item["deployment_assumption"]["expected_failure_observed"] is True
        assert item["own_suite"]["outcome"] == "passed" and item["own_suite"]["tests_failed"] == 0
        assert item["scope"]["files_changed"] == item["scope"]["files_declared"]
    checkout = by_id["checkout-display-major-units"]
    (failed,) = checkout["deployment_assumption"]["failed_cases"]
    assert (failed["case_id"], failed["actual"]) == ("displayed_total_usd", "$1000.00")
    assert "src/tax.ts" in checkout["scope"]["unchanged_verified"]
    assert "src/rewards.ts" in checkout["scope"]["unchanged_verified"]
    fraud = by_id["fraud-threshold-major-units"]
    assert sorted(case["case_id"] for case in fraud["deployment_assumption"]["failed_cases"]) == [
        "at_threshold_not_flagged",
        "below_threshold_not_flagged",
    ]
    assert validation["not_prepared"][0]["repository"] == "shockwave-stripe-reporting"


def test_provider_summary_exposes_no_consumer_private_details(demo_run: DemoRun) -> None:
    summary_text = (demo_run.results / "provider" / "restricted-summary.json").read_text(encoding="utf-8")
    summary = json.loads(summary_text)
    assert summary["visibility"] == "provider_restricted"
    forbidden: set[str] = set()
    for path in (demo_run.results / "consumers").glob("*/dependencies.json"):
        document = load(path)
        forbidden |= {document["repository"], document["commit_sha"], document["audience"]["consumer_org_name"]}
        forbidden |= {document["audience"]["consumer_org_id"], document["repository_snapshot_id"]}
        for dependency in document["dependencies"]:
            forbidden.add(dependency["id"])
            for item in dependency["evidence"]:
                if item["kind"] == "source":
                    forbidden |= {item["file"], Path(item["file"]).name, item["excerpt"], item["id"]}
        for control in document["negative_controls"]:
            forbidden |= {control["file"], Path(control["file"]).name}
    for path in (DEMO / "migrations").glob("*.patch"):
        forbidden |= {line[1:].strip() for line in path.read_text(encoding="utf-8").splitlines() if line.startswith(("+", "-")) and len(line.strip()) > 3}
        forbidden.add(path.name)
    for record in demo_run.raw_runs.glob("*.json"):
        log = load(record).get("log_tail", {"text": ""})  # install records carry no log tail
        forbidden |= {line.strip() for line in log["text"].splitlines() if len(line.strip()) > 12}
    forbidden.discard("")
    leaked = sorted(item for item in forbidden if item in summary_text)
    assert leaked == []
    keys = set(re.findall(r'"([a-z_]+)":', summary_text))
    assert not keys & {"file", "files", "line", "line_start", "line_end", "excerpt", "path", "patch", "log", "log_tail", "locations"}
    assert [item["label"] for item in summary["consumers"]] == ["Consumer 1", "Consumer 2", "Consumer 3"]
    assert summary["totals"]["by_verification_status"] == {"not_run": 1, "verified_regression": 2}


def test_run_records_persist_commands_counts_revisions_and_bounded_logs(demo_run: DemoRun) -> None:
    records = sorted((demo_run.results / "runs").glob("*.json"))
    assert len(records) == 16
    for path in records:
        record = load(path)
        assert re.fullmatch(r"[0-9a-f]{40}", record["commit_sha"]), path.name
        assert record["tests_run"] > 0, path.name
        assert record["duration_ms"] == 0 and "log_tail" not in record
        assert record["command"]["argv"][0] in ("python", "node")
        assert not any(os.path.isabs(part) for part in record["command"]["argv"]), path.name
        assert re.fullmatch(r"[0-9a-f]{64}", record["fixture"]["sha256"]), path.name
        raw = load(demo_run.raw_runs / path.name)
        assert len(raw["log_tail"]["text"].encode("utf-8")) <= 4096
        assert "sk_test_" not in raw["log_tail"]["text"]
    texts = [path.read_text(encoding="utf-8") for path in demo_run.results.rglob("*.json")]
    for text in texts:
        for absolute in (str(demo_run.temp_root), str(REPO_ROOT), str(Path.home())):
            assert absolute not in text


