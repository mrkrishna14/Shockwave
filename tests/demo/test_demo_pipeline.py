"""End to end: ``demo.py all`` (offline) into temporary directories, then ``demo.py reset``.

One session run feeds every test here: the normalized results must equal demo/expected/results
byte for byte; the inventory counts must equal an independent parse of the pinned bytes; exactly
two verified regressions (checkout "$10.00" vs "$0.10"; fraud above-threshold True vs False) with
their guard cases passing; the reporting control passes under both variants; the storage risk
stays not_run with its missing evidence; both migrations validate with the pinned caveat while
patched-vs-baseline failures are deployment-assumption evidence (never regressions); the provider
summary carries no consumer file names, paths, lines, excerpts, logs or patch text; and reset
removes only generated state. Nothing runs in the repository's demo/.work or demo/reports.
"""

from __future__ import annotations

import gzip
import hashlib
import json
import os
import re
import shutil
import subprocess
from dataclasses import dataclass
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
DEMO = REPO_ROOT / "demo"
EXPECTED = DEMO / "expected" / "results"
CLI = DEMO / "scripts" / "demo.py"
PIN = REPO_ROOT / "examples" / "provider" / "stripe" / "pin.json"
PINNED_PATCH_CAVEAT = (
    "The patch is pinned to the proposed contract: it is not backward compatible with current-contract "
    "responses unless made version-aware, so its deployment must be coordinated with the provider's cutover."
)
# Never changed by any demo command (node_modules and caches excluded from the hash).
PROTECTED = (
    "demo/templates",
    "demo/stripe-fixtures",
    "demo/expected",
    "demo/migrations",
    "demo/scenarios",
    "demo/stripe-sources.lock.json",
    "demo/consumer-repos.manifest.json",
    "examples/provider/stripe",
)
HTTP_METHODS = ("get", "put", "post", "delete", "options", "head", "patch", "trace")


def tree_digest(paths: tuple[str, ...]) -> str:
    digest = hashlib.sha256()
    for relative in paths:
        root = REPO_ROOT / relative
        files = [root] if root.is_file() else sorted(item for item in root.rglob("*") if item.is_file())
        for path in files:
            parts = path.relative_to(REPO_ROOT).parts
            if {"node_modules", "__pycache__", ".pytest_cache"} & set(parts) or path.name == ".DS_Store":
                continue
            digest.update("/".join(parts).encode() + b"\0" + path.read_bytes() + b"\0")
    return digest.hexdigest()


@dataclass(frozen=True)
class DemoRun:
    output: str
    results: Path  # copy of <reports>/results taken before reset
    raw_runs: Path  # copy of <reports>/runs taken before reset
    work_dir: Path
    reports_dir: Path
    reset_output: str
    temp_root: Path


def _run_cli(args: list[str], subprocess_env, timeout: int = 300) -> subprocess.CompletedProcess[str]:
    env = subprocess_env({"HOME": os.environ.get("HOME", "/")})
    return subprocess.run(
        [str(REPO_ROOT / ".venv" / "bin" / "python"), str(CLI), *args],
        cwd=REPO_ROOT,
        env=env,
        capture_output=True,
        text=True,
        timeout=timeout,
        check=False,
    )


@pytest.fixture(scope="module")
def demo_run(tmp_path_factory, subprocess_env, node_executable, git_executable) -> DemoRun:
    root = tmp_path_factory.mktemp("demo-all")
    work, reports, keep = root / "work", root / "reports", root / "kept"
    reports.mkdir()
    (reports / "README.md").write_text("checked-in README stand-in\n", encoding="utf-8")
    (reports / ".gitkeep").write_bytes(b"")
    (work / "unrelated").mkdir(parents=True)
    (work / "unrelated" / "keep.txt").write_text("not generated by demo.py\n", encoding="utf-8")
    before = tree_digest(PROTECTED)
    default_state = sorted(path.name for path in (DEMO / "reports").iterdir()) if (DEMO / "reports").is_dir() else []
    try:
        completed = _run_cli(["all", "--work-dir", str(work), "--reports-dir", str(reports)], subprocess_env)
        if completed.returncode != 0 and "npm ci failed" in completed.stderr:
            pytest.skip(f"the checkout's node packages are not in the npm cache (offline run): {completed.stderr[-300:]}")
        assert completed.returncode == 0, completed.stdout[-3000:] + completed.stderr[-3000:]
        shutil.copytree(reports / "results", keep / "results")
        shutil.copytree(reports / "runs", keep / "runs")
        reset = _run_cli(["reset", "--work-dir", str(work), "--reports-dir", str(reports)], subprocess_env)
        assert reset.returncode == 0, reset.stderr
        assert tree_digest(PROTECTED) == before, "a demo command changed a checked-in demo input"
        after_default = sorted(path.name for path in (DEMO / "reports").iterdir()) if (DEMO / "reports").is_dir() else []
        assert after_default == default_state, "the test run touched the repository's demo/reports"
        yield DemoRun(completed.stdout, keep / "results", keep / "runs", work, reports, reset.stdout, root)
    finally:
        shutil.rmtree(root, ignore_errors=True)


def load(path: Path) -> dict | list:
    return json.loads(path.read_text(encoding="utf-8"))


def run_record(demo_run: DemoRun, run_id: str) -> dict:
    return load(demo_run.results / "runs" / f"{run_id}.json")


def case(record: dict, case_id: str) -> dict:
    (match,) = [item for item in record["assertions"] if item["case_id"] == case_id]
    return match


